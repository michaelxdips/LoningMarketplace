export function productDeterministicId(index: number): string {
  // Pad the index to 12 digits:
  const padded = index.toString().padStart(12, '0');
  // Format as e3000000-0000-4000-8000-{padded}
  return `e3000000-0000-4000-8000-${padded}`;
}

